"""Package a private species source folder with the unmodified AnyBug Blender pipeline."""

import argparse
import json
import re
import shutil
import tempfile
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

SKILL = Path(__file__).resolve().parents[1]
PIPELINE = ("build.py", "geometry.py", "motion.py", "verify.py")


def prepare(source, slug, name, out):
    if not re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", slug) or not name.strip():
        raise ValueError("Supply a lowercase species slug and display name")
    if out.exists():
        raise ValueError("Choose a new project directory")
    for f in ("build.py", "behavior.py", "README.md"):
        if not (source / f).is_file() or (source / f).is_symlink():
            raise ValueError("Missing authored species file: " + f)
    runtime = SKILL / "assets/runtime"
    checkout = SKILL.parents[1]
    if not runtime.is_dir():
        runtime = checkout
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=out.parent) as temp:
        project = Path(temp) / "project"
        species = project / "specimens" / slug
        species.mkdir(parents=True)
        for p in sorted(source.iterdir()):
            if p.is_symlink():
                continue
            if p.is_file() and (
                p.name == "README.md"
                or re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*\.py", p.name)
            ):
                shutil.copyfile(p, species / p.name)
        # Include only the reviewed author files and runtime. Personal images and .env
        # stay out of the ZIP. Original materials should be generated by the builder.
        for f in ("rebuild.py", "LICENSE"):
            shutil.copyfile(runtime / f, project / f)
        (project / "pipeline").mkdir()
        for f in PIPELINE:
            shutil.copyfile(runtime / "pipeline" / f, project / "pipeline" / f)
        shutil.copyfile(SKILL / "scripts/finish.py", project / "finish.py")
        viewer = SKILL / "assets/viewer.html.gz"
        if viewer.is_file():
            shutil.copyfile(viewer, project / "viewer.html.gz")
        else:
            from portable_viewer import template
            import gzip

            (project / "viewer.html.gz").write_bytes(
                gzip.compress(template(checkout).encode(), mtime=0)
            )
        (project / "specimens/catalog.json").write_text(
            json.dumps([{"id": slug, "name": name}], indent=2) + "\n"
        )
        (project / "README.md").write_text(
            "# " + name + "\n\nInstall Blender 5.2 and Python 3.10 or later, then run "
            "`python3 finish.py` from this folder. Open `explore.html` in a WebGL 2 browser. "
            "The editable master, GLB, anatomy manifest and reference brief are under `specimens/"
            + slug
            + "/`.\n"
        )
        with ZipFile(project / (slug + "-blender-project.zip"), "x", ZIP_DEFLATED) as z:
            for p in sorted(project.rglob("*")):
                if p.is_file() and p.suffix != ".zip":
                    z.write(p, p.relative_to(project))
        project.rename(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--id", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    prepare(args.source, args.id, args.name, args.out)
